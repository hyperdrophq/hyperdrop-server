#!/usr/bin/env python3
"""Reads platforms/synology/arches.tsv, the Synology package table.

  arches.py families   one line per package to build, tab-separated:
                       DSM major, name, GOARCH, GOARM (- for none),
                       INFO arch, os_min_ver
  arches.py builds     the manifest build names, dsm<major>-<family>, one a
                       line, newest DSM generation first
  arches.py write      rewrites the generated blocks in
                       hyperdrop-site.nginx.conf and
                       website/downloads/synology/index.html

The generated blocks sit between BEGIN and END marker lines naming this
script; everything outside them is left as it is. site:check runs `write`
and fails on a diff, the way it checks the feeds.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
TABLE = os.path.join(HERE, "arches.tsv")
NGINX = os.path.join(HERE, "hyperdrop-site.nginx.conf")
PAGE = os.path.join(ROOT, "website", "downloads", "synology", "index.html")
MARK = "generated by platforms/synology/arches.py from arches.tsv"


def load(path=TABLE):
    """(generations, families, platforms, builds).

    generations: [(major, os_min_ver)] in file order.
    families: [(name, goarch, goarm, label)] in file order.
    platforms: [(name, family)] in file order.
    builds: [(major, name, goarch, goarm, info, os_min_ver)], one per
    package, generations in file order and families in file order within
    each."""
    generations, families, platforms = [], [], []
    for number, raw in enumerate(open(path), 1):
        line = raw.rstrip("\n")
        if not line.strip() or line.startswith("#"):
            continue
        fields = line.split("\t")
        where = f"{path}:{number}"
        if fields[0] == "dsm" and len(fields) == 3 and fields[1].isdigit():
            generations.append((fields[1], fields[2]))
        elif fields[0] == "family" and len(fields) == 7:
            families.append(tuple(fields[1:]))
        elif fields[0] == "platform" and len(fields) == 3:
            platforms.append(tuple(fields[1:]))
        else:
            sys.exit(f"{where}: want `dsm<TAB>major<TAB>os_min_ver`, "
                     "`family<TAB>name<TAB>goarch<TAB>goarm<TAB>majors<TAB>info<TAB>label` "
                     "or `platform<TAB>name<TAB>family`")
    majors = [g[0] for g in generations]
    if len(set(majors)) != len(majors):
        sys.exit(f"{path}: a dsm generation is listed twice")
    names = [f[0] for f in families]
    if len(set(names)) != len(names):
        sys.exit(f"{path}: a family is listed twice")
    seen = set()
    for name, family in platforms:
        if family not in names:
            sys.exit(f"{path}: platform {name} names an unknown family {family}")
        if name in seen:
            sys.exit(f"{path}: platform {name} is listed twice")
        seen.add(name)
    for name, _, _, family_majors, info, _ in families:
        for major in family_majors.split(","):
            if major not in majors:
                sys.exit(f"{path}: family {name} names an unknown dsm generation {major}")
        if ("7" in family_majors.split(",")) != (info != "-"):
            sys.exit(f"{path}: family {name} needs a DSM 7 INFO arch exactly when it is built for DSM 7")
    builds = []
    for major, osmin in generations:
        for name, goarch, goarm, family_majors, info, _ in families:
            if major not in family_majors.split(","):
                continue
            listed = " ".join(p for p, f in platforms if f == name)
            # DSM 6 matches INFO arch against the box's platform name.
            if major != "7" or info == "*":
                info = listed
            if not info:
                sys.exit(f"{path}: family {name} has no INFO arch for DSM {major}")
            builds.append((major, name, goarch, goarm, info, osmin))
    families = [(name, goarch, goarm, label) for name, goarch, goarm, _, _, label in families]
    return generations, families, platforms, builds


def build_name(major, family):
    return f"dsm{major}-{family}"


def nginx_block(families, platforms, builds):
    lines = ["map $arg_arch $hd_cpu {", '    default "";']
    for name, *_ in families:
        lines.append("")
        lines.append(f"    # The {name} package.")
        for platform, family in platforms:
            if family == name:
                lines.append(f"    {platform:<16} {name};")
    lines.append("}")
    lines.append("")
    lines.append("# One file per package: a DSM generation and a CPU.")
    lines.append('map "$arg_major:$hd_cpu" $hd_feed {')
    lines.append("    default     none;")
    for major, name, *_ in builds:
        key = f'"{major}:{name}"'
        lines.append(f"    {key:<11} {build_name(major, name)};")
    lines.append("}")
    return lines


def page_block(families, platforms, builds):
    lines = ["const architectures = ["]
    lines += [f"  {{arch:{json.dumps(name)}, label:{json.dumps(label)}}}," for name, _, _, label in families]
    lines[-1] = lines[-1].rstrip(",")
    lines.append("];")
    lines.append("const builds = [")
    lines += [f"  {{dsm:{major}, arch:{json.dumps(name)}}}," for major, name, *_ in builds]
    lines[-1] = lines[-1].rstrip(",")
    lines.append("];")
    lines.append("const platform = {")
    rows = []
    for name, *_ in families:
        row = "  "
        for platform, family in platforms:
            if family != name:
                continue
            item = f'{platform}:"{family}", '
            if len(row) + len(item) > 100:
                rows.append(row.rstrip())
                row = "  "
            row += item
        rows.append(row.rstrip())
    rows[-1] = rows[-1].rstrip(",")
    lines += rows
    lines.append("};")
    return lines


def splice(path, comment, block):
    """Replaces the lines between the BEGIN and END markers in path."""
    text = open(path).read()
    lines = text.split("\n")
    begin = [i for i, l in enumerate(lines) if l.strip() == f"{comment} BEGIN {MARK}"]
    end = [i for i, l in enumerate(lines) if l.strip() == f"{comment} END {MARK}"]
    if len(begin) != 1 or len(end) != 1 or begin[0] > end[0]:
        sys.exit(f"{path}: want one `{comment} BEGIN {MARK}` line and one END line after it")
    new = lines[: begin[0] + 1] + block + lines[end[0]:]
    out = "\n".join(new)
    if out != text:
        with open(path, "w") as f:
            f.write(out)
        print(f"wrote {os.path.relpath(path, ROOT)}")


def main(argv):
    _, families, platforms, builds = load()
    command = argv[1] if len(argv) > 1 else ""
    if command == "families":
        for build in builds:
            print("\t".join(build))
    elif command == "builds":
        for major, name, *_ in builds:
            print(build_name(major, name))
    elif command == "write":
        splice(NGINX, "#", nginx_block(families, platforms, builds))
        splice(PAGE, "//", page_block(families, platforms, builds))
    else:
        sys.exit(__doc__.strip())


if __name__ == "__main__":
    main(sys.argv)
