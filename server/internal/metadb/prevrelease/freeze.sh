#!/usr/bin/env bash
# freeze.sh <commit>: generate this package as the metadb of the server
# release built from <commit> (the "Release server X.Y.Z" commit).
#
# Every non-test .go file of server/internal/metadb at <commit> is copied here
# with its package clause renamed to prevrelease and a generated-code header,
# and release.go records the commit and the version its server/main.go
# declares. Only tests import this package, so the linker never ships it; it
# is what lets a rollback test run the published release's statements against
# a volume this tree wrote. Every update path restarts the previous binary
# when the new one does not come healthy, so from the second public release
# on, a volume each release writes must be one the release before it serves.
#
# The rollback test (server/internal/metadb/rollback_test.go) opens, serves
# and edits a volume this tree wrote with the frozen package. Re-run this at
# every server release, on the commit of the release the tree rolls back to.
# Never edit the output by hand.
set -euo pipefail

if [ $# -ne 1 ]; then
	echo "usage: $0 <commit>" >&2
	exit 2
fi
here="$(cd "$(dirname "$0")" && pwd)"
top="$(git -C "$here" rev-parse --show-toplevel)"
commit="$(git -C "$top" rev-parse --verify "$1^{commit}")"
src=server/internal/metadb

version="$(git -C "$top" show "$commit:server/main.go" |
	sed -n 's/^const version = "\([^"]*\)".*/\1/p')"
if [ -z "$version" ]; then
	echo "freeze.sh: no const version in server/main.go at $commit" >&2
	exit 1
fi

files="$(git -C "$top" ls-tree --name-only "$commit" "$src/" |
	grep '\.go$' | grep -v '_test\.go$' || true)"
if [ -z "$files" ]; then
	echo "freeze.sh: no Go files under $src at $commit" >&2
	exit 1
fi

# Drop the previous generation, keeping this script.
find "$here" -maxdepth 1 -name '*.go' -delete

header="// Code generated by freeze.sh from $commit; DO NOT EDIT."
for path in $files; do
	name="$(basename "$path")"
	# The live package's own doc comment describes the live store; it is
	# dropped, and release.go carries this package's.
	{
		printf '%s\n\n' "$header"
		git -C "$top" show "$commit:$path" |
			awk '
				/^\/\// { held = held $0 "\n"; next }
				/^package metadb$/ {
					if (held !~ /^\/\/ Package metadb /) printf "%s", held
					held = ""; print "package prevrelease"; next
				}
				{ printf "%s", held; held = ""; print }
				END { printf "%s", held }'
	} >"$here/$name"
	if ! grep -q '^package prevrelease$' "$here/$name"; then
		echo "freeze.sh: $path has no package metadb clause" >&2
		exit 1
	fi
done

# SQLite functions are registered process-wide by name, and the rollback
# test's binary links the live metadb too, which registers the same names
# at init, so each function this package registers is renamed
# prevrelease_<name>, in its registration and in every statement and comment
# naming it. Only statements name a function, never a stored schema object,
# so the volume reads the same; a frozen schema that names one is refused.
fns="$(sed -n 's/.*sqlite\.MustRegister[A-Za-z]*Function("\([A-Za-z0-9_]*\)".*/\1/p' "$here"/*.go | sort -u)"
for fn in $fns; do
	if grep -q "$fn" "$here/schema.go" "$here/additive.go"; then
		echo "freeze.sh: the frozen schema names the SQL function $fn" >&2
		exit 1
	fi
	mid="s/\([^A-Za-z0-9_]\)$fn\([^A-Za-z0-9_]\)/\1prevrelease_$fn\2/g"
	for f in "$here"/*.go; do
		sed -e "$mid" -e "$mid" -e "s/\([^A-Za-z0-9_]\)$fn\$/\1prevrelease_$fn/" "$f" >"$f.tmp"
		mv "$f.tmp" "$f"
	done
	if grep -qE "(^|[^A-Za-z0-9_])$fn([^A-Za-z0-9_]|\$)" "$here"/*.go; then
		echo "freeze.sh: $fn is still named after the rename" >&2
		exit 1
	fi
done

cat >"$here/release.go" <<GO
$header

// Package prevrelease is server/internal/metadb as server $version shipped
// it, frozen for the rollback tests and imported by tests alone, so no
// binary carries it. Every update path restarts the previous binary when
// the new one does not come healthy, so a volume this tree writes must stay
// one that release serves: the rollback test in server/internal/metadb runs
// this package's statements against such a volume. freeze.sh regenerates it
// from the release's commit at every server release; it is never edited by
// hand.
package prevrelease

// Version is the server release this package's metadb was frozen from, and
// Commit the commit that release was built from.
const (
	Version = "$version"
	Commit  = "$commit"
)
GO

gofmt -l "$here" | { if read -r f; then echo "freeze.sh: $f is not gofmt-clean" >&2; exit 1; fi; }
echo "froze $src at $commit (server $version) into $here"
